"""Render only public data into OS-native scripts; no remote Python required."""

from __future__ import annotations

import base64
import json
from importlib.resources import files

from .state import Device, Inventory, SetupError


def group_path(inventory: Inventory) -> str:
    return f"~/.ssh/setup-ssh/{inventory.group_id}"


def host_alias(inventory: Inventory, device: Device) -> str:
    return f"setup-ssh-{inventory.group_id}-{device.id}"


def quoted(value: str) -> str:
    # OpenSSH double-quoted tokens (including domain\\user on Windows).
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ssh_config(inventory: Inventory, source: Device) -> str:
    root = group_path(inventory)
    lines = ["# Generated by setup-ssh; edit the inventory, then run sync."]
    for destination in inventory.devices:
        if source.id == destination.id:
            continue
        algorithm = (destination.host_key or {}).get("type", "ssh-ed25519")
        if algorithm == "ssh-rsa":
            algorithm = "rsa-sha2-512,rsa-sha2-256"
        lines.extend(
            [
                f"Host {destination.name}",
                f"    HostName {destination.host.replace('%', '%%')}",
                f"    User {quoted(destination.user)}",
                f"    Port {destination.port}",
                f"    IdentityFile {quoted(root + '/id_ed25519')}",
                "    IdentitiesOnly yes",
                "    ForwardAgent no",
                "    StrictHostKeyChecking yes",
                f"    UserKnownHostsFile {quoted(root + '/known_hosts')}",
                f"    HostKeyAlias {host_alias(inventory, destination)}",
                f"    HostKeyAlgorithms {algorithm}",
                "",
            ]
        )
    lines.append("Host *\n")
    return "\n".join(lines)


def known_hosts(inventory: Inventory) -> str:
    lines = []
    for device in inventory.devices:
        if device.host_key is None:
            raise SetupError(f"{device.name} has no verified SSH host key. Run sync first.")
        lines.append(
            f"{host_alias(inventory, device)} {device.host_key['type']} {device.host_key['data']}"
        )
    return "\n".join(lines) + "\n"


def authorized_keys(inventory: Inventory, source: Device) -> str:
    lines = []
    for device in inventory.devices:
        if device.id == source.id:
            continue
        if device.public_key is None:
            raise SetupError(f"{device.name} has no managed public key. Run sync first.")
        lines.append(f"{device.public_key} setup-ssh:{inventory.group_id}:{device.id}")
    return "\n".join(lines) + ("\n" if lines else "")


def script(
    inventory: Inventory,
    device: Device,
    action: str,
    *,
    destination: Device | None = None,
    timeout: int = 10,
) -> str:
    if action not in {"prepare", "apply", "remove", "check"}:
        raise ValueError(f"Unknown action: {action}")
    payload = {
        "group": inventory.group_id,
        "device": device.id,
        "action": action,
        "timeout": timeout,
        "destination": destination.name if destination else "",
        "config": ssh_config(inventory, device) if action == "apply" else "",
        "known_hosts": known_hosts(inventory) if action == "apply" else "",
        "authorized_keys": authorized_keys(inventory, device) if action == "apply" else "",
    }
    if device.platform == "windows":
        encoded = base64.b64encode(json.dumps(payload).encode()).decode()
        template = files("setup_ssh").joinpath("templates/windows.ps1").read_text("utf-8")
        return template.replace("__PAYLOAD__", encoded)
    # The shell template decodes each value independently; no jq/Python dependency.
    encoded_values = []
    for key, value in payload.items():
        encoded = base64.b64encode(str(value).encode()).decode()
        encoded_values.append(f"{key.upper()}=$(decode '{encoded}')")
    template = files("setup_ssh").joinpath("templates/posix.sh").read_text("utf-8")
    return template.replace("__PAYLOAD__", "\n".join(encoded_values))
